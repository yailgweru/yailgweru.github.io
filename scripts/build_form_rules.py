#!/usr/bin/env python3
"""Generate firebase/firestore.rules from the forms defined in data.json.

Any section item whose `more.form` is set renders as a form in the hologram
sidebar and writes one document to its Firestore `collection`. The rules
generated here make every form collection create-only (nobody can read,
edit or delete submissions from the site) and check each document's fields
against the same definitions the page renders from: allowed keys, required
fields, max lengths, select options, and a server timestamp.

Deploy after changing a form:

    python scripts/update_site.py
    cd firebase && firebase deploy --only firestore:rules

Submissions are read in the Firebase console (Firestore > Data).
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_JSON = ROOT / "data.json"
RULES = ROOT / "firebase" / "firestore.rules"

STRING_TYPES = {"text", "email", "tel", "url", "textarea"}
TYPES = STRING_TYPES | {"select", "checkbox"}
NAME_RE = re.compile(r"^[a-z][a-zA-Z0-9]*$")
EMAIL_RE = r"^[^@\\s]+@[^@\\s]+\\.[^@\\s]+$"


def collect_forms(data):
    forms, errors = [], []
    for section in data["sections"]:
        for item in section.get("items", []):
            form = (item.get("more") or {}).get("form")
            if not form:
                continue
            where = f"{section['id']} › {item.get('label')}"
            coll = form.get("collection", "")
            if not NAME_RE.match(coll):
                errors.append(f"{where}: collection '{coll}' must be camelCase letters/digits")
            if any(f["collection"] == coll for _, f in forms):
                errors.append(f"{where}: collection '{coll}' is used by another form")
            names = set()
            for field in form.get("fields", []):
                n, t = field.get("name", ""), field.get("type")
                if not NAME_RE.match(n) or n == "createdAt":
                    errors.append(f"{where}: field name '{n}' must be camelCase and not 'createdAt'")
                if n in names:
                    errors.append(f"{where}: duplicate field '{n}'")
                names.add(n)
                if t not in TYPES:
                    errors.append(f"{where}: field '{n}' type '{t}' must be one of {sorted(TYPES)}")
                if t in STRING_TYPES and not isinstance(field.get("max"), int):
                    errors.append(f"{where}: field '{n}' needs an integer 'max' (used by both the page and the rules)")
                if t == "select" and not field.get("options"):
                    errors.append(f"{where}: select field '{n}' needs 'options'")
            if not form.get("fields"):
                errors.append(f"{where}: form has no fields")
            forms.append((where, form))
    return forms, errors


def quote(s):
    return "'" + str(s).replace("\\", "\\\\").replace("'", "\\'") + "'"


def field_check(f):
    n, t, req = f["name"], f["type"], bool(f.get("required"))
    v = f"d.{n}"
    if t == "checkbox":
        return f"{v} == true" if req else f"{v} is bool"
    if t == "select":
        options = list(f["options"]) + ([] if req else [""])
        return f"{v} in [{', '.join(quote(o) for o in options)}]"
    checks = [f"{v} is string", f"{v}.size() <= {f['max']}"]
    if req:
        checks.append(f"{v}.size() > 0")
    if t == "email":
        match = f"{v}.matches('{EMAIL_RE}')"
        checks.append(match if req else f"({v}.size() == 0 || {match})")
    return " && ".join(checks)


def build(forms):
    out = [
        "// GENERATED by scripts/build_form_rules.py from the `more.form` blocks in data.json.",
        "// Do not hand-edit. Change the form in data.json, run python scripts/update_site.py,",
        "// then deploy: cd firebase && firebase deploy --only firestore:rules",
        "rules_version = '2';",
        "service cloud.firestore {",
        "  match /databases/{database}/documents {",
    ]
    for where, form in forms:
        coll = form["collection"]
        fn = "valid" + coll[0].upper() + coll[1:]
        keys = [f["name"] for f in form["fields"]] + ["createdAt"]
        key_list = ", ".join(quote(k) for k in keys)
        checks = [
            f"d.keys().hasAll([{key_list}])",
            f"d.keys().hasOnly([{key_list}])",
            "d.createdAt == request.time",
        ] + [field_check(f) for f in form["fields"]]
        out += [
            "",
            f"    // {where}",
            f"    match /{coll}/{{docId}} {{",
            f"      allow create: if {fn}(request.resource.data);",
            "      allow read, update, delete: if false;",
            "    }",
            f"    function {fn}(d) {{",
            "      return " + "\n        && ".join(checks) + ";",
            "    }",
        ]
    out += [
        "",
        "    // Everything else is closed.",
        "    match /{path=**} {",
        "      allow read, write: if false;",
        "    }",
        "  }",
        "}",
    ]
    return "\n".join(out) + "\n"


def main():
    data = json.loads(DATA_JSON.read_text(encoding="utf-8"))
    forms, errors = collect_forms(data)
    if errors:
        print("build_form_rules.py found problems — rules not written:", file=sys.stderr)
        for e in errors:
            print("  - " + e, file=sys.stderr)
        sys.exit(1)
    text = build(forms)
    RULES.parent.mkdir(exist_ok=True)
    if RULES.exists() and RULES.read_text(encoding="utf-8") == text:
        print("firebase/firestore.rules already up to date.")
        return
    RULES.write_text(text, encoding="utf-8")
    print(f"firebase/firestore.rules written ({len(forms)} form collection(s)).")


if __name__ == "__main__":
    main()
