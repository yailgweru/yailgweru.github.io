#!/usr/bin/env python3
"""
Regenerate everything derived from assets/logo.png:

- assets/favicon/*         the favicon set (the 96px one doubles as the
                           brand-bar logo on the home page), tinified:
                           256-colour PNGs with dithering (libimagequant)
- assets/logo-texture.js   the 3D scene's logo-disc texture
- assets/share.jpg         every page's share image (og:image, steering D-16):
                           the logo centred on a 1200x630 white card, so link
                           previews show all of it on any background

update_site.py runs this automatically when logo.png is newer than these
files (or one is missing). Requires Pillow (pip install pillow).

Usage:
    python scripts/make_favicons.py
"""
import base64
import io
from pathlib import Path

from PIL import Image, features

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "assets" / "logo.png"
OUT = ROOT / "assets" / "favicon"
TEXTURE_JS = ROOT / "assets" / "logo-texture.js"
SHARE_JPG = ROOT / "assets" / "share.jpg"
SHARE_SIZE = (1200, 630)

# The 3D scene draws the logo on a white disc, so the texture needs no alpha
# channel: flattened onto white it can be a JPEG, about a quarter the size of
# the PNG with no visible difference at this size. 512px stays sharp when the
# camera zooms all the way in.
TEXTURE_SIZE = 512
TEXTURE_QUALITY = 85


def write_texture(im):
    logo = im.resize((TEXTURE_SIZE, TEXTURE_SIZE), Image.LANCZOS)
    flat = Image.new("RGB", logo.size, (255, 255, 255))
    flat.paste(logo, mask=logo.split()[3])
    buf = io.BytesIO()
    flat.save(buf, "JPEG", quality=TEXTURE_QUALITY, optimize=True)
    data_uri = "data:image/jpeg;base64," + base64.b64encode(buf.getvalue()).decode("ascii")
    # A data: URI (rather than a plain .jpg) because WebGL refuses to texture
    # an image it considers cross-origin, and Chrome treats every file:// path
    # as its own origin. Loading it from a script works over http(s) and when
    # index.html is opened from disk. Only the 3D view loads this file; the
    # lite view never downloads it.
    TEXTURE_JS.write_text(
        "// GENERATED by scripts/make_favicons.py from assets/logo.png. Do not hand-edit.\n"
        "// The 3D scene's logo-disc texture: a JPEG data: URI, so WebGL can use it under file:// too.\n"
        f'window.__LOGO_DATA_URI__ = "{data_uri}";\n',
        encoding="utf-8",
    )
    print(f"wrote {TEXTURE_JS.relative_to(ROOT)} ({len(buf.getvalue()) // 1024} KB JPEG)")


def write_share_card(im):
    card = Image.new("RGB", SHARE_SIZE, (255, 255, 255))
    logo = im.crop(im.getbbox())
    scale = min(SHARE_SIZE[1] * 0.82 / logo.height, SHARE_SIZE[0] * 0.82 / logo.width)
    logo = logo.resize((round(logo.width * scale), round(logo.height * scale)), Image.LANCZOS)
    card.paste(logo, ((SHARE_SIZE[0] - logo.width) // 2, (SHARE_SIZE[1] - logo.height) // 2), logo)
    card.save(SHARE_JPG, "JPEG", quality=85, optimize=True, progressive=True)
    print(f"wrote {SHARE_JPG.relative_to(ROOT)} ({SHARE_JPG.stat().st_size // 1024} KB)")


def save_tiny_png(im, path):
    """TinyPNG-style: a 256-colour palette with dithering (libimagequant, the
    pngquant engine) — about a third of the size, no visible difference."""
    method = Image.Quantize.LIBIMAGEQUANT if features.check("libimagequant") else Image.Quantize.FASTOCTREE
    im.quantize(colors=256, method=method).save(path, optimize=True)


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    im = Image.open(SRC).convert("RGBA")
    write_texture(im)
    write_share_card(im)

    # Trim transparent padding, then re-pad a little so the mark isn't
    # flush to the edge — keeps it legible at 16x16 in a browser tab.
    im = im.crop(im.getbbox())
    w, h = im.size
    side = max(w, h)
    pad = int(side * 0.06)
    square = Image.new("RGBA", (side + pad * 2, side + pad * 2), (0, 0, 0, 0))
    square.paste(im, ((side - w) // 2 + pad, (side - h) // 2 + pad), im)

    named_sizes = {
        16: "favicon-16x16.png",
        32: "favicon-32x32.png",
        48: "favicon-48x48.png",
        96: "favicon-96x96.png",
        180: "apple-touch-icon.png",
        192: "android-chrome-192x192.png",
        512: "android-chrome-512x512.png",
    }
    for size, name in named_sizes.items():
        save_tiny_png(square.resize((size, size), Image.LANCZOS), OUT / name)
        print("wrote", name)

    square.resize((256, 256), Image.LANCZOS).save(
        OUT / "favicon.ico", format="ICO", sizes=[(16, 16), (32, 32), (48, 48)]
    )
    print("wrote favicon.ico")


if __name__ == "__main__":
    main()
