#!/usr/bin/env python3
"""Sync data.json and the generated manifests into index.html's fallback blocks.

data.json stays the single source of truth for site content; index.html's
inline <script id="site-data"> block is a fallback copy used only when
fetch('data.json') is blocked (e.g. opening index.html via file://). The
INLINE-MANIFESTS block does the same for blogs/, team/ and
projects/manifest.json. Runs as part of `python scripts/update_site.py`.
"""
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_JSON = ROOT / "data.json"
INDEX_HTML = ROOT / "index.html"
MANIFESTS = {
    "blogs": ROOT / "blogs" / "manifest.json",
    "team": ROOT / "team" / "manifest.json",
    "projects": ROOT / "projects" / "manifest.json",
}

MANIFESTS_RE = re.compile(r"<!-- INLINE-MANIFESTS:START.*?<!-- INLINE-MANIFESTS:END -->", re.DOTALL)

BLOCK_RE = re.compile(
    r"<!-- INLINE-DATA:START.*?-->\s*"
    r"<script type=\"application/json\" id=\"site-data\">\n"
    r".*?\n"
    r"</script>\s*"
    r"<!-- INLINE-DATA:END -->",
    re.DOTALL,
)


def main():
    data = json.loads(DATA_JSON.read_text(encoding="utf-8"))
    html = INDEX_HTML.read_text(encoding="utf-8")

    if not BLOCK_RE.search(html):
        print("Could not find INLINE-DATA:START ... INLINE-DATA:END block in index.html", file=sys.stderr)
        sys.exit(1)

    payload = json.dumps(data, indent=2, ensure_ascii=False)
    replacement = (
        "<!-- INLINE-DATA:START — generated by scripts/inline_data.py from data.json. "
        "Run that script after editing data.json to keep this block in sync. It's a "
        "fallback the app uses only when fetch('data.json') fails (e.g. opening index.html "
        "via file://); data.json fetched over http(s) is still the live source used "
        "normally. Do not hand-edit. -->\n"
        "<script type=\"application/json\" id=\"site-data\">\n"
        f"{payload}\n"
        "</script>\n"
        "<!-- INLINE-DATA:END -->"
    )

    new_html = BLOCK_RE.sub(lambda _m: replacement, html)

    if not MANIFESTS_RE.search(new_html):
        print("Could not find INLINE-MANIFESTS:START ... INLINE-MANIFESTS:END block in index.html", file=sys.stderr)
        sys.exit(1)
    manifests = {
        name: json.loads(path.read_text(encoding="utf-8")) if path.exists() else []
        for name, path in MANIFESTS.items()
    }
    manifests_block = (
        "<!-- INLINE-MANIFESTS:START — generated by scripts/inline_data.py from blogs/, team/ and "
        "projects/manifest.json. file:// fallback only, like INLINE-DATA. Do not hand-edit. -->\n"
        "<script type=\"application/json\" id=\"site-manifests\">\n"
        f"{json.dumps(manifests, ensure_ascii=False)}\n"
        "</script>\n"
        "<!-- INLINE-MANIFESTS:END -->"
    )
    new_html = MANIFESTS_RE.sub(lambda _m: manifests_block, new_html)

    if new_html == html:
        print("index.html already up to date with data.json and manifests")
        return

    INDEX_HTML.write_text(new_html, encoding="utf-8")
    print("Synced data.json and manifests into index.html's inline fallback blocks.")


if __name__ == "__main__":
    main()
