#!/usr/bin/env python3
"""Build a static page for every team member and every project.

Each person and project is one JSON file; the filename is its slug:

  data/team/<slug>.json      ->  team/<slug>.html      + team/manifest.json
  data/projects/<slug>.json  ->  projects/<slug>.html  + projects/manifest.json

The pages are the canonical, crawlable copies (own URL, meta tags, JSON-LD).
The manifests feed the home page, where the same people and projects show
in the hologram sidebar and are deep-linkable as #team/<slug> and
#projects/<slug>.

Photos: leave "image" blank and drop assets/team/<slug>.jpg (or .jpeg,
.png, .webp) in place; it's picked up automatically. Same for project
images in assets/projects/ (optional).

Generated pages carry a GENERATED marker; a marked page whose JSON was
deleted is removed. Run via `python scripts/update_site.py` (or directly).
See CLAUDE.md "People and projects" for the field reference.
"""
import json
import re
import sys
from html import escape
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA_JSON = ROOT / "data.json"
TEMPLATE = ROOT / "scripts" / "_page_template.html"
SITE_ROOT = "https://yailgweru.github.io"
ORG_ID = SITE_ROOT + "/#organization"
ORG_NAME = "Young AI Leaders — Gweru Hub"
LOGO_ABS = SITE_ROOT + "/assets/logo.png"
LOGO_ALT = "Young AI Leaders Community logo — Gweru Hub"
IMAGE_EXTS = (".jpg", ".jpeg", ".png", ".webp")
SLUG_RE = re.compile(r"^[a-z0-9]+(?:-[a-z0-9]+)*$")
MARKER = "<!-- GENERATED by scripts/build_pages.py"

GROUPS = {"leadership": "Hub leadership", "member": "Hub member"}
OWNERSHIP = {"community": "Community project", "member": "Member project"}
STATUSES = {"": "", "planned": "Planned", "active": "Active", "completed": "Completed"}

errors = []


def fail(msg):
    errors.append(msg)


def slugify(text):
    """Same rule as the item-slug function in index.html's init()."""
    text = re.sub(r"[^a-z0-9\s-]", "", str(text).lower()).strip()
    return re.sub(r"[\s_-]+", "-", text)


def as_list(value):
    if not value:
        return []
    return value if isinstance(value, list) else [value]


def check_url(where, value):
    if value and not re.match(r"^https?://", value):
        fail(f"{where}: '{value}' must be a full URL starting with https://")


def resolve_image(where, kind, slug, value):
    """Explicit path wins; otherwise look for assets/<kind>/<slug>.<ext>."""
    if value:
        if re.match(r"^https?://", value):
            return value
        if not (ROOT / value).is_file():
            fail(f"{where}: image '{value}' does not exist")
        return value
    for ext in IMAGE_EXTS:
        candidate = Path("assets") / kind / f"{slug}{ext}"
        if (ROOT / candidate).is_file():
            return candidate.as_posix()
    return ""


def load_dir(kind):
    entries = []
    folder = ROOT / "data" / kind
    for path in sorted(folder.glob("*.json")):
        slug = path.stem
        where = path.relative_to(ROOT).as_posix()
        if not SLUG_RE.match(slug):
            fail(f"{where}: filename must be a lowercase-hyphenated slug (e.g. jane-doe.json)")
            continue
        try:
            entry = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            fail(f"{where}: invalid JSON ({e})")
            continue
        entry["slug"] = slug
        entry["_where"] = where
        entries.append(entry)
    return entries


def reserved_team_slugs():
    data = json.loads(DATA_JSON.read_text(encoding="utf-8"))
    team = next((s for s in data["sections"] if s.get("id") == "team"), {})
    return {slugify(it.get("label", "")) for it in team.get("items", [])}


def normalize_person(p, reserved):
    w = p["_where"]
    if not p.get("name"):
        fail(f"{w}: 'name' is required")
    if p.get("group") not in GROUPS:
        fail(f"{w}: 'group' must be one of {sorted(GROUPS)}")
    if p["slug"] in reserved:
        fail(f"{w}: slug '{p['slug']}' clashes with a Team section item; rename the file")
    for key in ("linkedin", "site"):
        check_url(f"{w} {key}", p.get(key, ""))
    bio = [str(t) for t in as_list(p.get("bio"))]
    return {
        "slug": p["slug"],
        "name": p.get("name", ""),
        "group": p.get("group", "member"),
        "order": p.get("order", 999),
        "role": p.get("role", ""),
        "image": resolve_image(w, "team", p["slug"], p.get("image", "")),
        "brief": p.get("brief", "") or (bio[0] if bio else ""),
        "bio": bio,
        "linkedin": p.get("linkedin", ""),
        "site": p.get("site", ""),
        "url": f"team/{p['slug']}.html",
        "projects": [],
    }


def normalize_project(p, people):
    w = p["_where"]
    if not p.get("title"):
        fail(f"{w}: 'title' is required")
    if not p.get("summary"):
        fail(f"{w}: 'summary' is required")
    if p.get("ownership") not in OWNERSHIP:
        fail(f"{w}: 'ownership' must be one of {sorted(OWNERSHIP)}")
    status = p.get("status", "") or ""
    if status not in STATUSES:
        fail(f"{w}: 'status' must be one of {sorted(s for s in STATUSES if s)} or blank")
    owners = []
    for slug in as_list(p.get("owners")):
        if slug not in people:
            fail(f"{w}: owner '{slug}' has no data/team/{slug}.json")
            continue
        owners.append({"slug": slug, "name": people[slug]["name"], "url": people[slug]["url"]})
    if p.get("ownership") == "member" and not owners:
        fail(f"{w}: a member-owned project needs at least one entry in 'owners'")
    links = []
    for i, link in enumerate(as_list(p.get("links"))):
        if not isinstance(link, dict) or not link.get("href"):
            fail(f"{w}: links[{i}] needs an 'href'")
            continue
        check_url(f"{w} links[{i}]", link["href"])
        links.append({"href": link["href"], "label": link.get("label") or "Learn more"})
    return {
        "slug": p["slug"],
        "title": p.get("title", ""),
        "ownership": p.get("ownership", "community"),
        "owners": owners,
        "status": status,
        "order": p.get("order", 999),
        "summary": p.get("summary", ""),
        "body": [str(t) for t in as_list(p.get("body"))],
        "image": resolve_image(w, "projects", p["slug"], p.get("image", "")),
        "links": links,
        "url": f"projects/{p['slug']}.html",
    }


def clip(text, limit=158):
    text = " ".join(str(text).split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:—-") + "…"


def initials(name):
    return "".join(w[0] for w in name.split()[:2]).upper() or "?"


def abs_url(path):
    return path if re.match(r"^https?://", path) else f"{SITE_ROOT}/{path}"


def social_row(p):
    links = []
    if p["linkedin"]:
        links.append((p["linkedin"], "linkedin.svg", "LinkedIn"))
    if p["site"]:
        links.append((p["site"], "website.svg", "Website"))
    if not links:
        return ""
    items = "".join(
        f'<a href="{escape(href, quote=True)}" target="_blank" rel="noopener" aria-label="{label} — {escape(p["name"], quote=True)}">'
        f'<img src="../assets/icons/{icon}" alt=""></a>'
        for href, icon, label in links
    )
    return f'<div class="social-row">{items}</div>'


def render(fill):
    html = TEMPLATE.read_text(encoding="utf-8")
    for key, value in fill.items():
        html = html.replace("{{" + key + "}}", value)
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", html)
    if leftover:
        fail(f"template tokens left unfilled: {sorted(set(leftover))}")
    return html


def person_page(p, projects_by_slug):
    canonical = f"{SITE_ROOT}/{p['url']}"
    label = GROUPS[p["group"]]
    if p["image"]:
        src = p["image"] if p["image"].startswith("http") else "../" + p["image"]
        photo = f'<img class="photo" src="{escape(src, quote=True)}" alt="{escape(p["name"], quote=True)}">'
    else:
        photo = f'<div class="avatar" aria-hidden="true">{escape(initials(p["name"]))}</div>'
    role = f'<div class="role">{escape(p["role"])}</div>' if p["role"] else ""
    main = (
        f'  <div class="person-head">{photo}<div><h1>{escape(p["name"])}</h1>{role}{social_row(p)}</div></div>\n'
        '  <div class="content">\n'
        + "".join(f"    <p>{escape(t)}</p>\n" for t in p["bio"])
    )
    if p["projects"]:
        main += "    <h2>Projects</h2>\n    <ul>\n"
        for slug in p["projects"]:
            pr = projects_by_slug[slug]
            main += f'      <li><a href="../{pr["url"]}">{escape(pr["title"])}</a> — {escape(pr["summary"])}</li>\n'
        main += "    </ul>\n"
    main += "  </div>"

    person = {
        "@type": "Person",
        "name": p["name"],
        "url": canonical,
        "memberOf": {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME, "url": SITE_ROOT + "/"},
    }
    if p["role"]:
        person["jobTitle"] = p["role"]
    if p["brief"]:
        person["description"] = p["brief"]
    if p["image"]:
        person["image"] = abs_url(p["image"])
    same_as = [u for u in (p["linkedin"], p["site"]) if u]
    if same_as:
        person["sameAs"] = same_as
    ld = {"@context": "https://schema.org", "@type": "ProfilePage", "url": canonical, "mainEntity": person}

    title = f"{p['name']} — {p['role']}" if p["role"] else p["name"]
    description = clip(f"{p['name']}{', ' + p['role'] if p['role'] else ''} at Young AI Leaders Gweru Hub, Zimbabwe. {p['brief']}")
    return render({
        "GENERATED_NOTE": f"{MARKER} from data/team/{p['slug']}.json — edit the JSON, not this file. -->",
        "TITLE_TAG": escape(f"{title} | Young AI Leaders Gweru Hub"),
        "OG_TITLE": escape(title, quote=True),
        "DESCRIPTION": escape(description, quote=True),
        "KEYWORDS": escape(", ".join([p["name"], "Young AI Leaders Gweru", "AI Zimbabwe", "Gweru tech hub"]), quote=True),
        "CANONICAL": canonical,
        "OG_TYPE": "profile",
        "IMAGE_ABS": LOGO_ABS,
        "IMAGE_ALT": LOGO_ALT,
        "JSON_LD": json.dumps(ld, indent=2, ensure_ascii=False),
        "BACK_HREF": f"../#team/{p['slug']}",
        "KICKER": label,
        "MAIN_HTML": main,
    })


def project_page(p):
    canonical = f"{SITE_ROOT}/{p['url']}"
    label = OWNERSHIP[p["ownership"]]
    meta = []
    if p["owners"]:
        names = " &amp; ".join(f'<a href="../{o["url"]}">{escape(o["name"])}</a>' for o in p["owners"])
        meta.append(("By " if p["ownership"] == "member" else "Led by ") + names)
    else:
        meta.append("Run by Young AI Leaders Gweru Hub")
    if p["status"]:
        meta.append(STATUSES[p["status"]])
    hero = ""
    if p["image"]:
        src = p["image"] if p["image"].startswith("http") else "../" + p["image"]
        hero = f'  <img class="hero" src="{escape(src, quote=True)}" alt="{escape(p["title"], quote=True)}">\n'
    main = (
        f'  <h1>{escape(p["title"])}</h1>\n'
        f'  <div class="meta">{" &middot; ".join(meta)}</div>\n'
        f"{hero}"
        '  <div class="content">\n'
        f'    <p><strong>{escape(p["summary"])}</strong></p>\n'
        + "".join(f"    <p>{escape(t)}</p>\n" for t in p["body"])
        + "".join(
            f'    <a class="cta" href="{escape(l["href"], quote=True)}"'
            + (' target="_blank" rel="noopener"' if l["href"].startswith("http") else "")
            + f'>{escape(l["label"])}</a>\n'
            for l in p["links"]
        )
        + "  </div>"
    )

    if p["owners"] and p["ownership"] == "member":
        creator = [{"@type": "Person", "name": o["name"], "url": f"{SITE_ROOT}/{o['url']}"} for o in p["owners"]]
        creator = creator[0] if len(creator) == 1 else creator
    else:
        creator = {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME}
    work = {
        "@context": "https://schema.org",
        "@type": "CreativeWork",
        "name": p["title"],
        "description": p["summary"],
        "url": canonical,
        "creator": creator,
        "publisher": {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME},
        "locationCreated": {"@type": "Place", "name": "Gweru, Midlands Province, Zimbabwe"},
        "genre": label,
    }
    if p["image"]:
        work["image"] = abs_url(p["image"])

    return render({
        "GENERATED_NOTE": f"{MARKER} from data/projects/{p['slug']}.json — edit the JSON, not this file. -->",
        "TITLE_TAG": escape(f"{p['title']} — {label} | Young AI Leaders Gweru Hub"),
        "OG_TITLE": escape(p["title"], quote=True),
        "DESCRIPTION": escape(clip(f"{p['summary']} A {label.lower()} of Young AI Leaders Gweru Hub, Zimbabwe."), quote=True),
        "KEYWORDS": escape(", ".join([p["title"], label, "Young AI Leaders Gweru", "AI Zimbabwe", "AI projects Zimbabwe"]), quote=True),
        "CANONICAL": canonical,
        "OG_TYPE": "article",
        "IMAGE_ABS": LOGO_ABS,
        "IMAGE_ALT": LOGO_ALT,
        "JSON_LD": json.dumps(work, indent=2, ensure_ascii=False),
        "BACK_HREF": f"../#projects/{p['slug']}",
        "KICKER": label,
        "MAIN_HTML": main,
    })


def write_if_changed(path, text, changed):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")
    changed.append(path.relative_to(ROOT).as_posix())


def remove_stale(folder, keep, changed):
    for path in folder.glob("*.html"):
        if path.stem in keep:
            continue
        head = path.read_text(encoding="utf-8")[:300]
        if MARKER in head:
            path.unlink()
            changed.append(f"{path.relative_to(ROOT).as_posix()} (removed)")


def main():
    reserved = reserved_team_slugs()
    people = {p["slug"]: normalize_person(p, reserved) for p in load_dir("team")}
    projects = [normalize_project(p, people) for p in load_dir("projects")]

    if errors:
        print("build_pages.py found problems — nothing was written:", file=sys.stderr)
        for e in errors:
            print("  - " + e, file=sys.stderr)
        sys.exit(1)

    projects.sort(key=lambda p: (p["ownership"] != "community", p["order"], p["title"].lower()))
    for pr in projects:
        for o in pr["owners"]:
            people[o["slug"]]["projects"].append(pr["slug"])
    team = sorted(people.values(), key=lambda p: (p["group"] != "leadership", p["order"], p["name"].lower()))
    projects_by_slug = {p["slug"]: p for p in projects}

    changed = []
    for p in team:
        write_if_changed(ROOT / p["url"], person_page(p, projects_by_slug), changed)
    for p in projects:
        write_if_changed(ROOT / p["url"], project_page(p), changed)
    remove_stale(ROOT / "team", {p["slug"] for p in team}, changed)
    remove_stale(ROOT / "projects", {p["slug"] for p in projects}, changed)

    for name, entries in (("team", team), ("projects", projects)):
        payload = json.dumps(entries, indent=2, ensure_ascii=False) + "\n"
        write_if_changed(ROOT / name / "manifest.json", payload, changed)

    print(f"{len(team)} people, {len(projects)} projects.")
    print("Updated: " + ", ".join(changed) if changed else "Pages and manifests already up to date.")


if __name__ == "__main__":
    main()
