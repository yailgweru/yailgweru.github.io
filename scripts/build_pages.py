#!/usr/bin/env python3
"""Render a standalone page for every team member and every project.

  data/team/<slug>.json      ->  team/<slug>.html
  data/projects/<slug>.json  ->  projects/<slug>.html

These pages are search-engine landing pages only (own canonical URL, meta
tags, JSON-LD, sitemap entry). Nothing on the site links to them: people
read the same content in the home page's hologram sidebar, which is
rendered into index.html by prerender_seo.py. The only links out of these
pages are deep links back into that sidebar (../#team/<slug>,
../#projects/<slug>).

Photos: leave "image" blank and drop assets/team/<slug>.jpg (or .jpeg,
.png, .webp) in place; it's picked up automatically. Same for project
images in assets/projects/ (optional).

Generated pages carry a GENERATED marker; a marked page whose JSON was
deleted is removed. Run via `python scripts/update_site.py`.
"""
import json
import re
from html import escape

import sys

from site_content import GROUPS, LOGO_ABS, LOGO_ALT, ORG_ID, ORG_NAME, OWNERSHIP, ROOT, SITE_ROOT, STATUSES, is_external, load, person_links

TEMPLATE = ROOT / "scripts" / "_page_template.html"
MARKER = "<!-- GENERATED by scripts/build_pages.py"


def clip(text, limit=158):
    text = " ".join(str(text).split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:—-") + "…"


def initials(name):
    return "".join(w[0] for w in name.split()[:2]).upper() or "?"


def abs_url(path):
    return path if is_external(path) else f"{SITE_ROOT}/{path}"


def rel_src(path):
    return path if is_external(path) else "../" + path


def social_row(p):
    links = person_links(p)
    if not links:
        return ""
    items = "".join(
        f'<a href="{escape(href, quote=True)}" target="_blank" rel="noopener" title="{escape(label, quote=True)}" aria-label="{escape(label, quote=True)} — {escape(p["name"], quote=True)}">'
        f'<img src="../assets/icons/{icon}" alt=""></a>'
        for href, icon, label in links
    )
    return f'<div class="social-row">{items}</div>'


def sdg_list(goals):
    items = "".join(
        f'<li><a href="{escape(g["url"], quote=True)}" target="_blank" rel="noopener">{escape(g["label"])}</a></li>' for g in goals
    )
    return f"    <ul>{items}</ul>\n"


def render(fill):
    html = TEMPLATE.read_text(encoding="utf-8")
    for key, value in fill.items():
        html = html.replace("{{" + key + "}}", value)
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", html)
    if leftover:
        raise SystemExit(f"_page_template.html tokens left unfilled: {sorted(set(leftover))}")
    return html


def person_page(p):
    canonical = f"{SITE_ROOT}/{p['page']}"
    if p["image"]:
        photo = f'<img class="photo" src="{escape(rel_src(p["image"]), quote=True)}" alt="{escape(p["name"], quote=True)}">'
    else:
        photo = f'<div class="avatar" aria-hidden="true">{escape(initials(p["name"]))}</div>'
    role = f'<div class="role">{escape(p["role"])}</div>' if p["role"] else ""
    main = (
        f'  <div class="person-head">{photo}<div><h1>{escape(p["name"])}</h1>{role}{social_row(p)}</div></div>\n'
        '  <div class="content">\n'
        + "".join(f"    <p>{escape(t)}</p>\n" for t in p["bio"])
    )
    if p["projects"]:
        main += "    <h2>Projects</h2>\n    <ul>\n"
        for pr in p["projects"]:
            main += f'      <li><a href="../#projects/{pr["slug"]}">{escape(pr["title"])}</a> ({escape(pr["role"])}) — {escape(pr["summary"])}</li>\n'
        main += "    </ul>\n"
        goals = {g["num"]: g for pr in p["projects"] for g in pr["sdgs"]}
        main += "    <h2>Works towards</h2>\n" + sdg_list([goals[n] for n in sorted(goals)])
    main += "  </div>"

    person = {
        "@type": "Person",
        "name": p["name"],
        "url": canonical,
        "memberOf": {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME, "url": SITE_ROOT + "/"},
    }
    if p["role"]:
        person["jobTitle"] = p["role"]
    if p["brief"]:
        person["description"] = p["brief"]
    if p["image"]:
        person["image"] = abs_url(p["image"])
    same_as = [href for href, _icon, _label in person_links(p)]
    if same_as:
        person["sameAs"] = same_as
    if p["projects"]:
        person["knowsAbout"] = sorted({g["label"] for pr in p["projects"] for g in pr["sdgs"]})
    ld = {"@context": "https://schema.org", "@type": "ProfilePage", "url": canonical, "mainEntity": person}

    title = f"{p['name']} — {p['role']}" if p["role"] else p["name"]
    description = clip(f"{p['name']}{', ' + p['role'] if p['role'] else ''} at Young AI Leaders Gweru Hub, Zimbabwe. {p['brief']}")
    return render({
        "GENERATED_NOTE": f"{MARKER} from data/team/{p['slug']}.json — edit the JSON, not this file. -->",
        "TITLE_TAG": escape(f"{title} | Young AI Leaders Gweru Hub"),
        "OG_TITLE": escape(title, quote=True),
        "DESCRIPTION": escape(description, quote=True),
        "KEYWORDS": escape(", ".join([p["name"], "Young AI Leaders Gweru", "AI Zimbabwe", "Gweru tech hub"]), quote=True),
        "CANONICAL": canonical,
        "OG_TYPE": "profile",
        "IMAGE_ABS": LOGO_ABS,
        "IMAGE_ALT": LOGO_ALT,
        "JSON_LD": json.dumps(ld, indent=2, ensure_ascii=False),
        "BACK_HREF": f"../#team/{p['slug']}",
        "KICKER": GROUPS[p["group"]],
        "MAIN_HTML": main,
    })


def project_page(p):
    canonical = f"{SITE_ROOT}/{p['page']}"
    label = OWNERSHIP[p["ownership"]]
    meta = []
    if p["owners"]:
        names = " &amp; ".join(f'<a href="../#team/{o["slug"]}">{escape(o["name"])}</a>' for o in p["owners"])
        meta.append(("By " if p["ownership"] == "member" else "Led by ") + names)
    if p["members"]:
        meta.append("with " + ", ".join(f'<a href="../#team/{m["slug"]}">{escape(m["name"])}</a>' for m in p["members"]))
    else:
        meta.append("Run by Young AI Leaders Gweru Hub")
    if p["status"]:
        meta.append(STATUSES[p["status"]])
    hero = ""
    if p["image"]:
        hero = f'  <img class="hero" src="{escape(rel_src(p["image"]), quote=True)}" alt="{escape(p["title"], quote=True)}">\n'
    main = (
        f'  <h1>{escape(p["title"])}</h1>\n'
        f'  <div class="meta">{" &middot; ".join(meta)}</div>\n'
        f"{hero}"
        '  <div class="content">\n'
        f'    <p><strong>{escape(p["summary"])}</strong></p>\n'
        + "".join(f"    <p>{escape(t)}</p>\n" for t in p["body"])
        + "".join(
            f'    <a class="cta" href="{escape(l["href"], quote=True)}" target="_blank" rel="noopener">{escape(l["label"])}</a>\n'
            for l in p["links"]
        )
        + "    <h2>UN Sustainable Development Goals</h2>\n"
        + sdg_list(p["sdgs"])
        + "  </div>"
    )

    if p["owners"] and p["ownership"] == "member":
        creator = [{"@type": "Person", "name": o["name"], "url": f"{SITE_ROOT}/{o['page']}"} for o in p["owners"]]
        creator = creator[0] if len(creator) == 1 else creator
    else:
        creator = {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME}
    work = {
        "@context": "https://schema.org",
        "@type": "CreativeWork",
        "name": p["title"],
        "description": p["summary"],
        "url": canonical,
        "creator": creator,
        "publisher": {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME},
        "locationCreated": {"@type": "Place", "name": "Gweru, Midlands Province, Zimbabwe"},
        "genre": label,
        "about": [{"@type": "Thing", "name": g["label"], "url": g["url"]} for g in p["sdgs"]],
        "keywords": ", ".join(g["label"] for g in p["sdgs"]),
    }
    contributors = ([] if p["ownership"] == "member" else p["owners"]) + p["members"]
    if contributors:
        work["contributor"] = [{"@type": "Person", "name": c["name"], "url": f"{SITE_ROOT}/{c['page']}"} for c in contributors]
    if p["image"]:
        work["image"] = abs_url(p["image"])

    return render({
        "GENERATED_NOTE": f"{MARKER} from data/projects/{p['slug']}.json — edit the JSON, not this file. -->",
        "TITLE_TAG": escape(f"{p['title']} — {label} | Young AI Leaders Gweru Hub"),
        "OG_TITLE": escape(p["title"], quote=True),
        "DESCRIPTION": escape(clip(f"{p['summary']} A {label.lower()} of Young AI Leaders Gweru Hub, Zimbabwe."), quote=True),
        "KEYWORDS": escape(", ".join([p["title"], label, "Young AI Leaders Gweru", "AI Zimbabwe", "AI projects Zimbabwe"] + [g["label"] for g in p["sdgs"]]), quote=True),
        "CANONICAL": canonical,
        "OG_TYPE": "article",
        "IMAGE_ABS": LOGO_ABS,
        "IMAGE_ALT": LOGO_ALT,
        "JSON_LD": json.dumps(work, indent=2, ensure_ascii=False),
        "BACK_HREF": f"../#projects/{p['slug']}",
        "KICKER": label,
        "MAIN_HTML": main,
    })


def write_if_changed(path, text, changed):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")
    changed.append(path.relative_to(ROOT).as_posix())


def remove_stale(folder, keep, changed):
    for path in folder.glob("*.html"):
        if path.stem not in keep and MARKER in path.read_text(encoding="utf-8")[:300]:
            path.unlink()
            changed.append(f"{path.relative_to(ROOT).as_posix()} (removed)")
    # Older builds wrote JSON manifests here for the browser to read; the
    # home page is now prerendered HTML, so they're no longer produced.
    old = folder / "manifest.json"
    if old.exists():
        old.unlink()
        changed.append(f"{old.relative_to(ROOT).as_posix()} (removed)")


def main():
    site = load()
    changed = []
    for p in site.team:
        write_if_changed(ROOT / p["page"], person_page(p), changed)
    for p in site.projects:
        write_if_changed(ROOT / p["page"], project_page(p), changed)
    remove_stale(ROOT / "team", {p["slug"] for p in site.team}, changed)
    remove_stale(ROOT / "projects", {p["slug"] for p in site.projects}, changed)
    print(f"{len(site.team)} people, {len(site.projects)} projects.")
    if site.warnings:
        print("Incomplete profiles (each person needs an ITU profile and at least 2 socials):", file=sys.stderr)
        for w in site.warnings:
            print("  - " + w, file=sys.stderr)
    print("Updated: " + ", ".join(changed) if changed else "Pages already up to date.")


if __name__ == "__main__":
    main()
