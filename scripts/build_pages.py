#!/usr/bin/env python3
"""Render a standalone page for every team member and every project.

  data/team/<slug>.json      ->  team/<slug>.html
  data/projects/<slug>.json  ->  projects/<slug>.html

These pages are search-engine landing pages only (own canonical URL, meta
tags, JSON-LD, sitemap entry). Nothing on the site links to them: people
read the same content in the home page's hologram sidebar, which is
rendered into index.html by prerender_seo.py. The only links out of these
pages are deep links back into that sidebar (../#team/<slug>,
../#projects/<slug>).

Photos: leave "image" blank and drop assets/team/<slug>.jpg (or .jpeg,
.png, .webp) in place; it's picked up automatically. Same for project
images in assets/projects/ (optional). Pages show tinified thumbnails of
them (images.py), never the originals.

Person pages are written to be found and quoted: a one-sentence factual
summary (who, role, hub, place, network, projects), an "At a glance" fact
list, and JSON-LD (ProfilePage + Person + BreadcrumbList) with the person's
@id, photo, profiles (sameAs) and created/updated dates.

Generated pages carry a GENERATED marker; a marked page whose JSON was
deleted is removed. Run via `python scripts/update_site.py`.
"""
import json
import re
import sys
from datetime import date
from html import escape

from images import largest, srcset
from site_content import (
    GROUPS, HUB_NAME, HUB_PLACE, LOGO_ALT, NETWORK_NAME, NETWORK_PARENT, ORG_ID, ORG_NAME, OWNERSHIP, ROOT,
    SHARE_IMAGE_ABS, SHARE_IMAGE_SIZE, SITE_ROOT, STATUSES, created, is_external, lastmod, load, person_links,
    person_summary,
)

TEMPLATE = ROOT / "scripts" / "_page_template.html"
MARKER = "<!-- GENERATED by scripts/build_pages.py"


def clip(text, limit=158):
    text = " ".join(str(text).split())
    if len(text) <= limit:
        return text
    return text[:limit].rsplit(" ", 1)[0].rstrip(",;:—-") + "…"


def initials(name):
    return "".join(w[0] for w in name.split()[:2]).upper() or "?"


def abs_url(path):
    return path if is_external(path) else f"{SITE_ROOT}/{path}"


def rel_src(path):
    return path if is_external(path) else "../" + path


def social_row(p):
    links = person_links(p)
    if not links:
        return ""
    items = "".join(
        f'<a href="{escape(href, quote=True)}" target="_blank" rel="noopener" title="{escape(label, quote=True)}" aria-label="{escape(label, quote=True)} — {escape(p["name"], quote=True)}">'
        f'<img src="../assets/icons/{icon}" width="16" height="16" alt=""></a>'
        for href, icon, label in links
    )
    return f'<div class="social-row">{items}</div>'


def a(text):
    return escape(str(text), quote=True)


def display_date(iso):
    d = date.fromisoformat(iso)
    return f"{d.day} {d.strftime('%B %Y')}"


def image_object(variants, caption):
    best = largest(variants)
    return {"@type": "ImageObject", "url": f"{SITE_ROOT}/{best['src']}", "width": best["w"], "height": best["h"], "caption": caption}




def sdg_list(goals):
    items = "".join(
        f'<li><a href="{escape(g["url"], quote=True)}" target="_blank" rel="noopener">{escape(g["label"])}</a></li>' for g in goals
    )
    return f"    <ul>{items}</ul>\n"


def render(fill):
    html = TEMPLATE.read_text(encoding="utf-8")
    for key, value in fill.items():
        html = html.replace("{{" + key + "}}", value)
    leftover = re.findall(r"\{\{[A-Z_]+\}\}", html)
    if leftover:
        raise SystemExit(f"_page_template.html tokens left unfilled: {sorted(set(leftover))}")
    return html


def person_page(p):
    canonical = f"{SITE_ROOT}/{p['page']}"
    person_id = canonical + "#person"
    alt = f"{p['name']}, {p['role']} at {HUB_NAME}" if p["role"] else f"{p['name']}, {HUB_NAME}"
    if p["photo"]:
        small = largest(p["photo"], at_most=192)
        photo = (
            f'<img class="photo" src="../{a(small["src"])}" srcset="{a(srcset(p["photo"], "../"))}" '
            f'sizes="(max-width: 640px) 72px, 96px" width="96" height="96" alt="{a(alt)}" decoding="async">'
        )
    elif p["image"]:  # an external photo URL
        photo = f'<img class="photo" src="{a(rel_src(p["image"]))}" width="96" height="96" alt="{a(alt)}">'
    else:
        photo = f'<div class="avatar" aria-hidden="true">{escape(initials(p["name"]))}</div>'
    role = f'<div class="role">{escape(p["role"])}</div>' if p["role"] else ""
    modified = lastmod(p["source"], p["image"] if p["photo"] else "")
    summary = person_summary(p)
    goals = {g["num"]: g for pr in p["projects"] for g in pr["sdgs"]}

    main = (
        f'  <div class="person-head">{photo}<div><h1>{escape(p["name"])}</h1>{role}{social_row(p)}</div></div>\n'
        '  <div class="content">\n'
        f'    <p class="lead">{escape(summary)}</p>\n'
        + "".join(f"    <p>{escape(t)}</p>\n" for t in p["bio"])
    )
    if p["projects"]:
        main += "    <h2>Projects</h2>\n    <ul>\n"
        for pr in p["projects"]:
            main += f'      <li><a href="../#projects/{pr["slug"]}">{escape(pr["title"])}</a> ({escape(pr["role"])}) — {escape(pr["summary"])}</li>\n'
        main += "    </ul>\n"
    facts = []
    if p["role"]:
        facts.append(("Role", escape(p["role"])))
    facts.append(("Membership", f"{escape(GROUPS[p['group']])}, {escape(HUB_NAME)}"))
    facts.append(("Hub location", escape(HUB_PLACE)))
    facts.append(("Network", f"{escape(NETWORK_NAME)}, {escape(NETWORK_PARENT)}"))
    if goals:
        facts.append(("Works towards", " · ".join(
            f'<a href="{a(g["url"])}" target="_blank" rel="noopener">{escape(g["label"])}</a>' for g in (goals[n] for n in sorted(goals))
        )))
    links = person_links(p)
    if links:
        facts.append(("Profiles", " · ".join(
            f'<a href="{a(href)}" target="_blank" rel="noopener">{escape(label)}</a>' for href, _icon, label in links
        )))
    facts.append(("Profile updated", f'<time datetime="{modified}">{display_date(modified)}</time>'))
    main += "    <h2>At a glance</h2>\n    <dl class=\"facts\">\n" + "".join(
        f"      <dt>{label}</dt><dd>{value}</dd>\n" for label, value in facts
    ) + "    </dl>\n  </div>"

    person = {
        "@type": "Person",
        "@id": person_id,
        "name": p["name"],
        "url": canonical,
        "mainEntityOfPage": canonical,
        "description": p["brief"] or summary,
        "memberOf": {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME, "url": SITE_ROOT + "/"},
    }
    if p["role"]:
        person["jobTitle"] = p["role"]
    if p["photo"]:
        person["image"] = image_object(p["photo"], alt)
    elif p["image"]:
        person["image"] = abs_url(p["image"])
    same_as = [href for href, _icon, _label in links]
    if same_as:
        person["sameAs"] = same_as
    if goals:
        person["knowsAbout"] = [goals[n]["label"] for n in sorted(goals)]
    title = f"{p['name']} — {p['role']}" if p["role"] else p["name"]
    ld = {
        "@context": "https://schema.org",
        "@graph": [
            {
                "@type": "ProfilePage",
                "@id": canonical,
                "url": canonical,
                "name": f"{title} | {HUB_NAME}",
                "inLanguage": "en-ZW",
                "isPartOf": {"@id": SITE_ROOT + "/#website"},
                "dateCreated": created(p["source"]),
                "dateModified": modified,
                "mainEntity": {"@id": person_id},
                "breadcrumb": {"@id": canonical + "#breadcrumb"},
            },
            person,
            {
                "@type": "BreadcrumbList",
                "@id": canonical + "#breadcrumb",
                "itemListElement": [
                    {"@type": "ListItem", "position": 1, "name": HUB_NAME, "item": SITE_ROOT + "/"},
                    {"@type": "ListItem", "position": 2, "name": p["name"], "item": canonical},
                ],
            },
        ],
    }

    description = clip(f"{p['name']}{', ' + p['role'] if p['role'] else ''} at {HUB_NAME}, a youth-led AI community in Gweru, Zimbabwe. {p['brief']}")
    keywords = [p["name"], f"{p['name']} {HUB_NAME}", p["role"], HUB_NAME, "Young AI Leaders Gweru", "AI Zimbabwe", "Gweru tech hub"]
    keywords += [pr["title"] for pr in p["projects"]]
    return render({
        "GENERATED_NOTE": f"{MARKER} from data/team/{p['slug']}.json — edit the JSON, not this file. -->",
        "TITLE_TAG": escape(f"{title} | {HUB_NAME}"),
        "OG_TITLE": escape(title, quote=True),
        "DESCRIPTION": escape(description, quote=True),
        "KEYWORDS": escape(", ".join(k for k in keywords if k), quote=True),
        "CANONICAL": canonical,
        "OG_TYPE": "profile",
        "IMAGE_ABS": SHARE_IMAGE_ABS,
        "IMAGE_W": str(SHARE_IMAGE_SIZE[0]),
        "IMAGE_H": str(SHARE_IMAGE_SIZE[1]),
        "IMAGE_ALT": LOGO_ALT,
        "JSON_LD": json.dumps(ld, indent=2, ensure_ascii=False),
        "BACK_HREF": f"../#team/{p['slug']}",
        "KICKER": GROUPS[p["group"]],
        "MAIN_HTML": main,
    })


def project_page(p):
    canonical = f"{SITE_ROOT}/{p['page']}"
    label = OWNERSHIP[p["ownership"]]
    meta = []
    if p["owners"]:
        names = " &amp; ".join(f'<a href="../#team/{o["slug"]}">{escape(o["name"])}</a>' for o in p["owners"])
        meta.append(("By " if p["ownership"] == "member" else "Led by ") + names)
    if p["members"]:
        meta.append("with " + ", ".join(f'<a href="../#team/{m["slug"]}">{escape(m["name"])}</a>' for m in p["members"]))
    else:
        meta.append("Run by Young AI Leaders Gweru Hub")
    if p["status"]:
        meta.append(STATUSES[p["status"]])
    hero = ""
    if p["hero"]:
        first = largest(p["hero"], at_most=960)
        hero = (
            f'  <img class="hero" src="../{a(first["src"])}" srcset="{a(srcset(p["hero"], "../"))}" '
            f'sizes="(max-width: 720px) calc(100vw - 32px), 680px" width="{first["w"]}" height="{first["h"]}" '
            f'alt="{a(p["title"])}" fetchpriority="high" decoding="async">\n'
        )
    elif p["image"]:
        hero = f'  <img class="hero" src="{a(rel_src(p["image"]))}" alt="{a(p["title"])}">\n'
    main = (
        f'  <h1>{escape(p["title"])}</h1>\n'
        f'  <div class="meta">{" &middot; ".join(meta)}</div>\n'
        f"{hero}"
        '  <div class="content">\n'
        f'    <p><strong>{escape(p["summary"])}</strong></p>\n'
        + "".join(f"    <p>{escape(t)}</p>\n" for t in p["body"])
        + "".join(
            f'    <a class="cta" href="{escape(l["href"], quote=True)}" target="_blank" rel="noopener">{escape(l["label"])}</a>\n'
            for l in p["links"]
        )
        + "    <h2>UN Sustainable Development Goals</h2>\n"
        + sdg_list(p["sdgs"])
        + "  </div>"
    )

    if p["owners"] and p["ownership"] == "member":
        creator = [{"@type": "Person", "@id": f"{SITE_ROOT}/{o['page']}#person", "name": o["name"], "url": f"{SITE_ROOT}/{o['page']}"} for o in p["owners"]]
        creator = creator[0] if len(creator) == 1 else creator
    else:
        creator = {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME}
    work = {
        "@context": "https://schema.org",
        "@type": "CreativeWork",
        "@id": canonical + "#project",
        "name": p["title"],
        "description": p["summary"],
        "url": canonical,
        "creator": creator,
        "publisher": {"@type": "Organization", "@id": ORG_ID, "name": ORG_NAME},
        "locationCreated": {"@type": "Place", "name": "Gweru, Midlands Province, Zimbabwe"},
        "genre": label,
        "about": [{"@type": "Thing", "name": g["label"], "url": g["url"]} for g in p["sdgs"]],
        "keywords": ", ".join(g["label"] for g in p["sdgs"]),
    }
    contributors = ([] if p["ownership"] == "member" else p["owners"]) + p["members"]
    if contributors:
        work["contributor"] = [{"@type": "Person", "@id": f"{SITE_ROOT}/{c['page']}#person", "name": c["name"], "url": f"{SITE_ROOT}/{c['page']}"} for c in contributors]
    if p["hero"]:
        work["image"] = image_object(p["hero"], p["title"])
    elif p["image"]:
        work["image"] = abs_url(p["image"])
    work["dateCreated"] = created(p["source"])
    work["dateModified"] = lastmod(p["source"], p["image"] if p["hero"] else "")

    return render({
        "GENERATED_NOTE": f"{MARKER} from data/projects/{p['slug']}.json — edit the JSON, not this file. -->",
        "TITLE_TAG": escape(f"{p['title']} — {label} | Young AI Leaders Gweru Hub"),
        "OG_TITLE": escape(p["title"], quote=True),
        "DESCRIPTION": escape(clip(f"{p['summary']} A {label.lower()} of Young AI Leaders Gweru Hub, Zimbabwe."), quote=True),
        "KEYWORDS": escape(", ".join([p["title"], label, "Young AI Leaders Gweru", "AI Zimbabwe", "AI projects Zimbabwe"] + [g["label"] for g in p["sdgs"]]), quote=True),
        "CANONICAL": canonical,
        "OG_TYPE": "article",
        "IMAGE_ABS": SHARE_IMAGE_ABS,
        "IMAGE_W": str(SHARE_IMAGE_SIZE[0]),
        "IMAGE_H": str(SHARE_IMAGE_SIZE[1]),
        "IMAGE_ALT": LOGO_ALT,
        "JSON_LD": json.dumps(work, indent=2, ensure_ascii=False),
        "BACK_HREF": f"../#projects/{p['slug']}",
        "KICKER": label,
        "MAIN_HTML": main,
    })


def write_if_changed(path, text, changed):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and path.read_text(encoding="utf-8") == text:
        return
    path.write_text(text, encoding="utf-8")
    changed.append(path.relative_to(ROOT).as_posix())


def remove_stale(folder, keep, changed):
    for path in folder.glob("*.html"):
        if path.stem not in keep and MARKER in path.read_text(encoding="utf-8")[:300]:
            path.unlink()
            changed.append(f"{path.relative_to(ROOT).as_posix()} (removed)")
    # Older builds wrote JSON manifests here for the browser to read; the
    # home page is now prerendered HTML, so they're no longer produced.
    old = folder / "manifest.json"
    if old.exists():
        old.unlink()
        changed.append(f"{old.relative_to(ROOT).as_posix()} (removed)")


def main():
    site = load()
    changed = []
    for p in site.team:
        write_if_changed(ROOT / p["page"], person_page(p), changed)
    for p in site.projects:
        write_if_changed(ROOT / p["page"], project_page(p), changed)
    remove_stale(ROOT / "team", {p["slug"] for p in site.team}, changed)
    remove_stale(ROOT / "projects", {p["slug"] for p in site.projects}, changed)
    print(f"{len(site.team)} people, {len(site.projects)} projects.")
    if site.warnings:
        print(
            "Incomplete profiles (each person needs an ITU profile and at least 2 socials; "
            "a photo and a 60–150 word bio help search engines and AI answers know them):",
            file=sys.stderr,
        )
        for w in site.warnings:
            print("  - " + w, file=sys.stderr)
    print("Updated: " + ", ".join(changed) if changed else "Pages already up to date.")


if __name__ == "__main__":
    main()
