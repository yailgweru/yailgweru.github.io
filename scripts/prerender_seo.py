#!/usr/bin/env python3
"""Render the home page's content (and the blog listing) into static HTML.

The JSON sources (data.json, data/team, data/projects, blogs/manifest.json)
are build inputs only — the browser never reads them. This script renders
everything the visitor and search engines see into marker blocks:

  index.html        INLINE-SEO-HEAD   title/description/keywords/OG/Twitter/canonical/RSS
                    INLINE-LD-JSON    Organization + WebSite JSON-LD @graph
                    INLINE-BRAND      brand badge + hint text
                    INLINE-CONTENT    #hub-content: every section, item and sidebar
                                      panel as semantic HTML. Crawlers read it as-is;
                                      the 3D scene and hologram sidebar are built from
                                      it at runtime (no JSON fetches).
  blogs/index.html  INLINE-BLOG-LIST  post cards (JS filters them in place)

Nothing here links to the standalone person/project/post pages: their
content is shown in the sidebar, reached through #<section>/<slug> deep
links. Runs as part of `python scripts/update_site.py`.

The panel markup produced here is what openSide() in index.html clones and
wires up (person cards, forms, post fetches) — keep the two in sync.
"""
import json
import re
import sys
from html import escape

from site_content import ROOT, SITE_ROOT, is_external, load

INDEX_HTML = ROOT / "index.html"
BLOG_INDEX_HTML = ROOT / "blogs" / "index.html"
RERUN_NOTE = "Rerun python scripts/update_site.py after editing data.json, data/ or a blog post. Do not hand-edit."


def e(text):
    return escape(str(text or ""), quote=True)


def block_re(name):
    return re.compile(r"<!-- " + name + r":START.*?<!-- " + name + r":END -->", re.DOTALL)


def replace_block(html, name, body, path):
    pattern = block_re(name)
    if not pattern.search(html):
        print(f"Could not find {name}:START ... {name}:END block in {path.name}", file=sys.stderr)
        sys.exit(1)
    wrapped = f"<!-- {name}:START — generated by scripts/prerender_seo.py. {RERUN_NOTE} -->\n{body}\n<!-- {name}:END -->"
    return pattern.sub(lambda _m: wrapped, html)


# ---------- head ----------

def build_head_block(site):
    seo = site["seo"]
    canonical = seo["canonicalUrl"]
    title = seo.get("title") or site["title"]
    description = seo.get("description", "")
    keywords = seo.get("keywords", [])
    keywords = ", ".join(keywords) if isinstance(keywords, list) else keywords
    image = seo.get("ogImage", "")
    alt = seo.get("ogImageAlt", "")
    site_name = f"{site.get('brand', {}).get('name', '')} — Gweru Hub"
    lines = [
        f"<title>{escape(title)}</title>",
        f'<meta name="description" content="{e(description)}">',
        f'<meta name="keywords" content="{e(keywords)}">',
        f'<link rel="canonical" href="{e(canonical)}">',
        f'<link rel="alternate" type="application/rss+xml" title="{e(site_name)} — Blog" href="{e(SITE_ROOT)}/feed.xml">',
        '<meta property="og:type" content="website">',
        f'<meta property="og:url" content="{e(canonical)}">',
        f'<meta property="og:title" content="{e(title)}">',
        f'<meta property="og:description" content="{e(description)}">',
        f'<meta property="og:image" content="{e(image)}">',
        f'<meta property="og:image:alt" content="{e(alt)}">' if alt else None,
        f'<meta property="og:locale" content="{e(seo.get("locale", "en_ZW"))}">',
        f'<meta property="og:site_name" content="{e(site_name)}">',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{e(title)}">',
        f'<meta name="twitter:description" content="{e(description)}">',
        f'<meta name="twitter:image" content="{e(image)}">',
        f'<meta name="twitter:image:alt" content="{e(alt)}">' if alt else None,
        f'<meta name="twitter:site" content="{e(seo["twitterHandle"])}">' if seo.get("twitterHandle") else None,
    ]
    return "\n".join(l for l in lines if l)


def build_jsonld_block(site):
    seo = site["seo"]
    canonical = seo["canonicalUrl"]
    description = seo.get("description", "")
    image = seo.get("ogImage", "")
    graph = [
        {
            "@type": "Organization",
            "@id": canonical + "#organization",
            "name": f"{site.get('brand', {}).get('name', '')} — Gweru Hub",
            "alternateName": ["Young AI Leaders Gweru", "YAL Gweru Hub"],
            "url": canonical,
            "logo": {"@type": "ImageObject", "url": image},
            "description": description,
            "sameAs": ["https://luma.com/user/yailgweru"],
            "areaServed": [{"@type": "Country", "name": "Zimbabwe"}, {"@type": "Place", "name": "Southern Africa"}],
            "location": {
                "@type": "Place",
                "name": "Gweru",
                "address": {"@type": "PostalAddress", "addressLocality": "Gweru", "addressRegion": "Midlands Province", "addressCountry": "ZW"},
            },
            "knowsAbout": ["Artificial Intelligence", "Social Innovation", "Youth Empowerment", "Technology in Zimbabwe", "AI for Good", "Community Impact", "Ethical AI"],
            "memberOf": {"@type": "Organization", "name": "AI for Good (ITU)"},
        },
        {
            "@type": "WebSite",
            "@id": canonical + "#website",
            "url": canonical,
            "name": seo.get("title") or site["title"],
            "description": description,
            "publisher": {"@id": canonical + "#organization"},
            "inLanguage": "en-ZW",
        },
    ]
    payload = json.dumps({"@context": "https://schema.org", "@graph": graph}, indent=2, ensure_ascii=False)
    return f'<script type="application/ld+json" id="ld-json">\n{payload}\n</script>'


def build_brand_block(site, logo):
    brand = site.get("brand", {})
    return (
        '<div class="brand">\n'
        f'  <img id="brand-logo" src="{e(logo)}" alt="{e(brand.get("name", ""))} logo">\n'
        f'  <div>\n    <div class="t1">{escape(brand.get("name", ""))}</div>\n    <div class="t2">{escape(brand.get("tagline", ""))}</div>\n  </div>\n'
        "</div>\n"
        f'<div class="hint" id="hint">{escape(site.get("hint", ""))}</div>'
    )


# ---------- sidebar panels (cloned by openSide() in index.html) ----------
# Images use data-src so the hidden content tree doesn't download anything;
# openSide() swaps data-src -> src when a panel opens.

def initials(name):
    return "".join(w[0] for w in name.split()[:2]).upper() or "?"


def photo(p):
    if p.get("image"):
        return f'<img data-src="{e(p["image"])}" alt="{e(p["name"])}">'
    return f'<div class="avatar" aria-hidden="true">{escape(initials(p["name"]))}</div>'


def social_row(p):
    links = []
    if p.get("linkedin"):
        links.append((p["linkedin"], "linkedin.svg", "LinkedIn"))
    if p.get("site"):
        links.append((p["site"], "website.svg", "Website"))
    if not links:
        return ""
    return '<div class="social-row">' + "".join(
        f'<a href="{e(href)}" target="_blank" rel="noopener" aria-label="{label} — {e(p["name"])}"><img data-src="assets/icons/{icon}" alt=""></a>'
        for href, icon, label in links
    ) + "</div>"


def link_attrs(href):
    return f'href="{e(href)}"' + (' target="_blank" rel="noopener"' if is_external(href) else "")


def paragraphs(items, cls=""):
    attr = f' class="{cls}"' if cls else ""
    return "".join(f"<p{attr}>{escape(t)}</p>" for t in items if t)


def chips(links):
    return '<div class="owner-list">' + "".join(f'<a href="{e(h)}">{escape(t)}</a>' for h, t in links) + "</div>"


def people_html(more, section):
    people = section.get("people") or {}
    want = more.get("people")
    profiles = people.get("leadership", []) if want in ("leadership", "all") else []
    members = people.get("members", []) if want in ("members", "all") else []
    labels = bool(profiles and members)
    out = ""
    if profiles:
        if labels:
            out += f'<div class="side-label">{escape(more.get("profilesLabel", "Leadership"))}</div>'
        for p in profiles:
            role = f'<div class="p-role">{escape(p["role"])}</div>' if p["role"] else ""
            out += (
                f'<div class="profile" data-person="{e(p["slug"])}">{photo(p)}<div>'
                f'<button type="button" class="p-name">{escape(p["name"])}</button>{role}'
                f'<div class="p-bio">{paragraphs(p["bio"])}</div>{social_row(p)}</div></div>'
            )
    if members:
        if labels:
            out += f'<div class="side-label">{escape(more.get("gridLabel", "Official members"))}</div>'
        out += '<div class="member-grid">'
        for m in members:
            role = f'<div class="m-role">{escape(m["role"])}</div>' if m["role"] else ""
            brief = f'<div class="m-brief">{escape(m["brief"])}</div>' if m["brief"] else ""
            out += (
                f'<div class="member" data-person="{e(m["slug"])}">{photo(m)}'
                f'<button type="button" class="m-name">{escape(m["name"])}</button>{role}{brief}{social_row(m)}</div>'
            )
        out += "</div>"
    if not profiles and not members and more.get("empty"):
        out += f"<p>{escape(more['empty'])}</p>"
    return out


def form_html(form):
    fields = ""
    for f in form["fields"]:
        req = " required" if f.get("required") else ""
        maxlen = f' maxlength="{int(f["max"])}"' if f.get("max") else ""
        label = f"<span>{escape(f['label'])}</span>"
        name = e(f["name"])
        if f["type"] == "checkbox":
            fields += f'<label class="f-field f-check"><input type="checkbox" name="{name}"{req}>{label}</label>'
            continue
        if f["type"] == "textarea":
            control = f'<textarea name="{name}"{req}{maxlen}></textarea>'
        elif f["type"] == "select":
            opts = '<option value="">Choose one…</option>' + "".join(f'<option value="{e(o)}">{escape(o)}</option>' for o in f["options"])
            control = f'<select name="{name}"{req}>{opts}</select>'
        else:
            auto = {"email": "email", "tel": "tel"}.get(f["type"]) or ("name" if f["name"] == "name" else "")
            auto = f' autocomplete="{auto}"' if auto else ""
            control = f'<input type="{e(f["type"])}" name="{name}"{req}{maxlen}{auto}>'
        fields += f'<label class="f-field">{label}{control}</label>'
    return (
        '<template class="form-tpl">'
        f'<form class="side-form" data-collection="{e(form["collection"])}" data-success="{e(form.get("success", ""))}" data-offline="{e(form.get("offline", ""))}">'
        f"{fields}"
        '<input class="f-hp" name="website" tabindex="-1" autocomplete="off" aria-hidden="true">'
        f'<button type="submit" class="f-submit">{escape(form.get("submitLabel", "Send"))}</button>'
        '<div class="f-status" role="status" aria-live="polite"></div>'
        "</form></template>"
    )


def panel_html(section, item):
    more = item["more"]
    out = ""
    person = more.get("person")
    if person:
        out += f'<div class="profile">{photo(person)}<div><div class="p-bio">{paragraphs(person["bio"] or [person["brief"]])}</div>{social_row(person)}</div></div>'
        if person["projects"]:
            out += '<div class="side-label">Projects</div>' + chips([(f"#projects/{pr['slug']}", pr["title"]) for pr in person["projects"]])
    if more.get("image"):
        out += f'<img class="side-hero" data-src="{e(more["image"])}" alt="{e(more.get("title") or item["label"])}">'
    if more.get("lead"):
        out += f"<p><strong>{escape(more['lead'])}</strong></p>"
    out += paragraphs(more.get("body", []))
    project = more.get("project")
    if project:
        if project["owners"]:
            out += f'<div class="side-label">{"Owned by" if project["ownership"] == "member" else "Led by"}</div>'
            out += chips([(f"#team/{o['slug']}", o["name"]) for o in project["owners"]])
        out += "".join(f'<a class="side-link" {link_attrs(l["href"])}>{escape(l["label"])}</a>' for l in project["links"])
    if more.get("people"):
        out += people_html(more, section)
    if more.get("fetch"):
        out += f'<div class="side-fetch" data-fetch="{e(more["fetch"])}">{paragraphs([more.get("fallback", "")])}</div>'
    if more.get("form"):
        out += form_html(more["form"])
    link = more.get("link")
    if link:
        out += f'<a class="side-link" {link_attrs(link["href"])}>{escape(link.get("label") or "Read more →")}</a>'
    return out


def item_html(section, item, hidden=False):
    more = item.get("more")
    attrs = [f'data-slug="{e(item["slug"])}"', f'data-label="{e(item["label"])}"']
    if item.get("group"):
        attrs.append(f'data-group="{e(item["group"])}"')
    if item.get("link") and not more:
        attrs.append(f'data-link="{e(item["link"])}"')
    if more:
        attrs.append(f'data-kicker="{e(more.get("kicker") or section["title"])}"')
        attrs.append(f'data-title="{e(more.get("title") or item["label"])}"')
        attrs.append(f'data-meta="{e(more.get("meta", ""))}"')
    if hidden:
        attrs.append("data-hidden")
    heading = escape(item["label"])
    if item.get("link") and not more:
        heading = f'<a {link_attrs(item["link"])}>{heading}</a>'
    html = f'<article {" ".join(attrs)}><h3>{heading}</h3>'
    if item.get("detail"):
        html += f'<p class="detail">{escape(item["detail"])}</p>'
    if more:
        # Hidden items (one per person) live in a <template>: their text already
        # appears in the leadership/member panels, so it isn't indexed twice.
        tag = "template" if hidden else "div"
        html += f'<{tag} class="panel">{panel_html(section, item)}</{tag}>'
    return html + "</article>"


def build_content(site_ns):
    site, data = site_ns.site, site_ns.data
    seo = site["seo"]
    fb = data.get("firebase") or {}
    attrs = " ".join(
        f'data-firebase-{k}="{e(fb.get(v, ""))}"'
        for k, v in (("api-key", "apiKey"), ("auth-domain", "authDomain"), ("project-id", "projectId"), ("app-id", "appId"))
    )
    html = f"<h1>{escape(seo.get('h1') or seo.get('title') or site['title'])}</h1>"
    html += paragraphs([seo.get("description", ""), seo.get("intro", "")])
    for s in site_ns.sections:
        pos = ",".join(str(v) for v in s["pos"])
        color = int(str(s["color"]).replace("0x", ""), 16) if isinstance(s["color"], str) else s["color"]
        html += (
            f'\n<section id="{e(s["id"])}" data-id="{e(s["id"])}" data-title="{e(s["title"])}" data-sub="{e(s.get("sub", ""))}" '
            f'data-color="{color}" data-pos="{pos}" data-empty="{e(s.get("empty", ""))}">'
            f'<h2>{escape(s["title"])} — {escape(s.get("sub", ""))}</h2>'
        )
        for item in s.get("items", []):
            html += "\n" + item_html(s, item)
        for item in s.get("hidden", []):
            html += "\n" + item_html(s, item, hidden=True)
        html += "\n</section>"
    return f'<main id="hub-content" class="sr-only" aria-label="Young AI Leaders Gweru Hub" {attrs}>\n{html}\n</main>'


# ---------- blog listing ----------

def build_blog_grid(posts):
    """Static cards; blogs/index.html's script filters them via their data-*
    attributes. Cards open the post in the home page's sidebar."""
    if not posts:
        return '<p class="empty">No posts yet — check back soon.</p>'
    cards = []
    for p in posts:
        authors = p.get("authors") or ([p["author"]] if p.get("author") else [])
        tags = " ".join("#" + t for t in (p.get("tags") or [])[:3])
        meta = escape(p["date"])
        if p.get("author"):
            meta += f" &middot; by {escape(p['author'])}"
        if tags:
            meta += f" &middot; {escape(tags)}"
        search = " ".join([p["title"], p.get("excerpt", ""), p.get("author", "")] + (p.get("tags") or []) + (p.get("topics") or []))
        cards.append(
            f'<a class="card" href="../#blogs/{e(p["slug"])}" data-search="{e(search.lower())}" '
            f'data-authors="{e("|".join(authors))}" data-featured="{"1" if p.get("featured") else "0"}">'
            f'<img src="../{e(p["image"])}" alt="{e(p["title"])}" loading="lazy">'
            f'<div class="card-body"><h2>{escape(p["title"])}</h2><p>{escape(p.get("excerpt", ""))}</p>'
            f'<div class="meta">{meta}</div></div></a>'
        )
    return "\n".join(cards)


def main():
    site_ns = load()
    site = site_ns.site
    changed = []

    html = INDEX_HTML.read_text(encoding="utf-8")
    new = replace_block(html, "INLINE-SEO-HEAD", build_head_block(site), INDEX_HTML)
    new = replace_block(new, "INLINE-LD-JSON", build_jsonld_block(site), INDEX_HTML)
    new = replace_block(new, "INLINE-BRAND", build_brand_block(site, site_ns.data.get("logo", "assets/logo.png")), INDEX_HTML)
    new = replace_block(new, "INLINE-CONTENT", build_content(site_ns), INDEX_HTML)
    if new != html:
        INDEX_HTML.write_text(new, encoding="utf-8")
        changed.append("index.html")

    blog = BLOG_INDEX_HTML.read_text(encoding="utf-8")
    new_blog = replace_block(blog, "INLINE-BLOG-LIST", build_blog_grid(site_ns.posts), BLOG_INDEX_HTML)
    if new_blog != blog:
        BLOG_INDEX_HTML.write_text(new_blog, encoding="utf-8")
        changed.append("blogs/index.html")

    print("Rendered: " + ", ".join(changed) if changed else "Rendered HTML already up to date.")


if __name__ == "__main__":
    main()
