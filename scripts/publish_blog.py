#!/usr/bin/env python3
"""
Publish a markdown draft (blogs/<slug>.md) as a static blog post
(blogs/<slug>.html), wiring up its images and manifest entry.

The markdown draft and its source images (blogs/images/) are gitignored and
stay local; only the compiled output is committed and pushed: blogs/<slug>.html,
assets/blogs/<slug>/ and blogs/manifest.json. The images published there are
tinified copies at 480/960/1440 px (scripts/images.py), never the originals:
the page picks the right size with srcset, and inline images load lazily. sitemap.xml is regenerated by
scripts/update_site.py (build_sitemap.py), which you run after publishing.
See CLAUDE.md for the authoring workflow.

Usage:
    python scripts/publish_blog.py blogs/teaching-ai-in-our-own-languages.md
    python scripts/publish_blog.py blogs/*.md   (shell-expanded, publishes each)

Requires: PyYAML, Markdown, Pillow  (pip install pyyaml markdown pillow)
"""
import json
import re
import shutil
import sys
from datetime import datetime
from html import escape
from pathlib import Path
from xml.sax.saxutils import escape as xml_escape

import markdown
import yaml

from images import BLOG_WIDTHS, PASSTHROUGH, largest, srcset, used_names, variants

ROOT = Path(__file__).resolve().parent.parent
BLOGS_DIR = ROOT / "blogs"
ASSETS_BLOGS_DIR = ROOT / "assets" / "blogs"
TEMPLATE_PATH = ROOT / "scripts" / "_blog_template.html"
MANIFEST_PATH = BLOGS_DIR / "manifest.json"
SITE_ROOT = "https://yailgweru.github.io"
SHARE_IMAGE_ABS = f"{SITE_ROOT}/assets/share.jpg"  # steering D-16: the logo card, made by make_favicons.py
# The post column: .wrap is 720px wide with 20px padding (16px on phones).
CONTENT_SIZES = "(max-width: 720px) calc(100vw - 32px), 680px"

REQUIRED_FIELDS = ["title", "date", "topics", "tags", "image"]


def slugify(text):
    text = re.sub(r"[^a-zA-Z0-9\s-]", "", text).strip().lower()
    return re.sub(r"[\s_-]+", "-", text)


def parse_frontmatter(md_path):
    raw = md_path.read_text(encoding="utf-8")
    if not raw.startswith("---"):
        raise ValueError(f"{md_path} is missing YAML frontmatter (must start with '---').")
    parts = raw.split("---", 2)
    if len(parts) < 3:
        raise ValueError(f"{md_path} has malformed frontmatter (need opening and closing '---').")
    meta = yaml.safe_load(parts[1]) or {}
    body = parts[2].strip()
    if not body:
        raise ValueError(f"{md_path} has no body content after the frontmatter.")

    missing = [f for f in REQUIRED_FIELDS if not meta.get(f)]
    if missing:
        raise ValueError(f"{md_path} frontmatter is missing required field(s): {', '.join(missing)}")

    meta["slug"] = slugify(str(meta.get("slug") or meta["title"]))
    meta.setdefault("excerpt", "")

    # Posts carry 1 or 2 authors: either `authors: [A, B]` or `author: A`
    # (a string also splits on '&' / ',' / ' and ').
    authors = meta.get("authors") or meta.get("author")
    if not authors:
        raise ValueError(f"{md_path} frontmatter needs `author:` or `authors:` (1 or 2 names).")
    if isinstance(authors, str):
        authors = [a.strip() for a in re.split(r"\s*(?:&|,|\band\b)\s*", authors) if a.strip()]
    if not 1 <= len(authors) <= 2:
        raise ValueError(f"{md_path}: posts have 1 or 2 authors, got {len(authors)}: {authors}")
    meta["authors"] = authors
    meta["author"] = " & ".join(authors)

    if isinstance(meta["tags"], str):
        meta["tags"] = [t.strip() for t in meta["tags"].split(",") if t.strip()]
    if isinstance(meta["topics"], str):
        meta["topics"] = [t.strip() for t in meta["topics"].split(",") if t.strip()]

    date_obj = meta["date"]
    if not isinstance(date_obj, datetime):
        date_obj = datetime.strptime(str(date_obj), "%Y-%m-%d")
    meta["date_obj"] = date_obj

    return meta, body


IMG_RE = re.compile(r"!\[([^\]]*)\]\(([^)\s]+)\)")


def img_tag(items, alt, extra):
    """<img> for published variants: a srcset of the sizes, the ~960px one as
    the fallback src, and width/height so the page doesn't jump as it loads."""
    if not items[0]["w"]:  # GIF/SVG, copied as they are
        return f'<img src="../{escape(items[0]["src"])}" alt="{escape(alt)}" {extra}>'
    default = largest(items, at_most=960)
    return (
        f'<img src="../{escape(default["src"])}" srcset="{escape(srcset(items, "../"))}" sizes="{CONTENT_SIZES}" '
        f'width="{default["w"]}" height="{default["h"]}" alt="{escape(alt)}" {extra}>'
    )


def localize_images(body, meta, draft_dir, out_img_dir):
    """Publish every locally-referenced image into assets/blogs/<slug>/ as
    tinified 480/960/1440 px copies (images.py) and point the post at them:
    inline images become <img> tags with a srcset that load lazily."""
    seen = {}
    kept = set()  # file names in out_img_dir that this post uses

    def publish_image(src):
        if src in seen:
            return seen[src]
        src_path = (draft_dir / src).resolve()
        if not src_path.is_file():
            raise FileNotFoundError(f"Image not found: {src_path}")
        out_img_dir.mkdir(parents=True, exist_ok=True)
        if src_path.suffix.lower() in PASSTHROUGH:  # animated GIF / SVG: as is
            shutil.copyfile(src_path, out_img_dir / src_path.name)
            kept.add(src_path.name)
            items = [{"src": f"assets/blogs/{meta['slug']}/{src_path.name}", "w": 0, "h": 0}]
        else:
            items = variants(src_path, BLOG_WIDTHS, out_dir=out_img_dir)
        seen[src] = items
        return items

    def repl(match):
        alt, src = match.group(1), match.group(2)
        if re.match(r"^https?://", src):
            return match.group(0)
        return img_tag(publish_image(src), alt, 'loading="lazy" decoding="async"')

    new_body = IMG_RE.sub(repl, body)

    # Hero image (frontmatter `image:`): the top of the page, so not lazy.
    hero_src = str(meta["image"])
    if re.match(r"^https?://", hero_src):
        meta["image_rel"] = hero_src
        meta["images"] = []
        meta["hero_html"] = f'<img class="hero" src="{escape(hero_src)}" alt="{escape(meta["title"])}" fetchpriority="high">'
    else:
        items = publish_image(hero_src)
        meta["image_rel"] = "../" + (largest(items, at_most=960)["src"])
        meta["images"] = items if items[0]["w"] else []
        meta["hero_html"] = img_tag(items, meta["title"], 'class="hero" fetchpriority="high" decoding="async"')
    # Drop images left over from an earlier publish of this post.
    kept |= used_names(out_img_dir)
    if out_img_dir.is_dir():
        for f in out_img_dir.iterdir():
            if f.is_file() and f.name not in kept:
                f.unlink()
    # Share image (og:image / twitter:image / JSON-LD) is always the hub logo
    # card for brand consistency (D-16); the hero only appears on the page.
    meta["image_abs"] = SHARE_IMAGE_ABS
    return new_body



def dedupe_keywords(meta):
    """tags + topics, dropping case/punctuation variants of the same term
    (e.g. 'ai-for-good' vs 'AI for Good') — keeps the first occurrence."""
    seen = set()
    result = []
    for t in meta["tags"] + meta["topics"]:
        key = re.sub(r"[^a-z0-9]", "", t.lower())
        if key not in seen:
            seen.add(key)
            result.append(t)
    return result


def author_node(name):
    # Named people are Person; house bylines like 'Hub Team' stay Organization.
    kind = "Organization" if name.endswith("Team") else "Person"
    return {"@type": kind, "name": name}


def build_json_ld(meta, canonical):
    author_nodes = [author_node(a) for a in meta["authors"]]
    graph = {
        "@context": "https://schema.org",
        "@type": "BlogPosting",
        "headline": meta["title"],
        "description": meta["excerpt"],
        "image": meta["image_abs"],
        "datePublished": meta["date_obj"].strftime("%Y-%m-%d"),
        "author": author_nodes[0] if len(author_nodes) == 1 else author_nodes,
        "publisher": {
            "@type": "Organization",
            "name": "Young AI Leaders — Gweru Hub",
            "logo": {"@type": "ImageObject", "url": f"{SITE_ROOT}/assets/logo.png"},
        },
        "keywords": ", ".join(dedupe_keywords(meta)),
        "articleSection": meta["topics"][0] if meta["topics"] else "",
        "mainEntityOfPage": canonical,
    }
    return json.dumps(graph, indent=2)


def render_post(meta, body_html, canonical):
    template = TEMPLATE_PATH.read_text(encoding="utf-8")
    keywords = dedupe_keywords(meta)
    tag_pills = "".join(f'<span class="tag">#{xml_escape(t)}</span>' for t in meta["tags"])
    topic_tags = "\n".join(f'<meta property="article:tag" content="{xml_escape(t)}">' for t in keywords)
    article_author_tags = "\n".join(f'<meta property="article:author" content="{xml_escape(a)}">' for a in meta["authors"])
    replacements = {
        "{{TITLE}}": xml_escape(meta["title"]),
        "{{EXCERPT}}": xml_escape(meta["excerpt"]),
        "{{TAGS_CSV}}": xml_escape(", ".join(keywords)),
        "{{AUTHOR}}": xml_escape(meta["author"]),
        "{{ARTICLE_AUTHOR_TAGS}}": article_author_tags,
        "{{CANONICAL}}": canonical,
        "{{IMAGE_ABS}}": meta["image_abs"],
        "{{IMAGE_ALT}}": "Young AI Leaders Community logo — Gweru Hub",
        "{{HERO_IMG}}": meta["hero_html"],
        "{{DATE_ISO}}": meta["date_obj"].strftime("%Y-%m-%d"),
        "{{DATE_DISPLAY}}": meta["date_obj"].strftime("%-d %B %Y") if sys.platform != "win32" else meta["date_obj"].strftime("%#d %B %Y"),
        "{{TAG_PILLS}}": tag_pills,
        "{{TOPIC_TAGS}}": topic_tags,
        "{{JSON_LD}}": build_json_ld(meta, canonical),
        "{{CONTENT_HTML}}": body_html,
    }
    for token, value in replacements.items():
        template = template.replace(token, value)
    return template


def update_manifest(meta):
    posts = json.loads(MANIFEST_PATH.read_text(encoding="utf-8")) if MANIFEST_PATH.exists() else []
    posts = [p for p in posts if p["slug"] != meta["slug"]]
    posts.append({
        "slug": meta["slug"],
        "title": meta["title"],
        "date": meta["date_obj"].strftime("%Y-%m-%d"),
        "author": meta["author"],
        "authors": meta["authors"],
        "featured": bool(meta.get("featured")),
        "topics": meta["topics"],
        "tags": meta["tags"],
        "image": meta["image_rel"].replace("../", ""),
        "images": meta["images"],
        "excerpt": meta["excerpt"],
    })
    posts.sort(key=lambda p: p["date"], reverse=True)
    MANIFEST_PATH.write_text(json.dumps(posts, indent=2) + "\n", encoding="utf-8")


def publish(md_path):
    md_path = Path(md_path).resolve()
    meta, body = parse_frontmatter(md_path)
    slug = meta["slug"]
    out_img_dir = ASSETS_BLOGS_DIR / slug
    body = localize_images(body, meta, md_path.parent, out_img_dir)

    body_html = markdown.markdown(body, extensions=["fenced_code", "tables", "footnotes"])
    canonical = f"{SITE_ROOT}/blogs/{slug}.html"

    BLOGS_DIR.mkdir(parents=True, exist_ok=True)
    out_path = BLOGS_DIR / f"{slug}.html"
    out_path.write_text(render_post(meta, body_html, canonical), encoding="utf-8")

    update_manifest(meta)

    print(f"Published: {out_path.relative_to(ROOT)}")
    print(f"Hero image: {meta['image_rel'].replace('../', '')}")
    print("Updated: blogs/manifest.json")
    title = meta["title"]
    print("\nNext: refresh the generated blocks and sitemap, review, then commit")
    print("(the .md draft stays local; it's gitignored) —")
    print("  python scripts/update_site.py")
    print(f'  git add blogs/{slug}.html assets/blogs/{slug} blogs/manifest.json blogs/index.html index.html feed.xml sitemap.xml')
    print(f'  git commit -m "Add blog post: {title}"')


if __name__ == "__main__":
    if len(sys.argv) < 2:
        print(__doc__)
        sys.exit(1)
    for arg in sys.argv[1:]:
        publish(arg)
